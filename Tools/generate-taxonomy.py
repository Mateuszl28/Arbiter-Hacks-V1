#!/usr/bin/env python3
"""Turns the vendored Open Food Facts taxonomies into Swift.

The material tree is not ours to invent. BinMate used to carry a hand written one,
and hand writing it produced exactly the failure you would expect: identifiers that
look plausible and do not exist. `en:pp-polypropylene` was a guess; the real entry is
`en:pp-5-polypropylene`, with the recycling code in the middle. Seven of those guesses
were the seven commonest plastics on earth, so every plastic with good data resolved
to nothing and fell into residual waste.

So the tree is generated from the published taxonomy instead, and a test fails if any
entry in it cannot be placed. Run ./Tools/refresh-taxonomy.sh to pull a new snapshot.

Two things are deliberately not mechanical:

  * Open Food Facts is a DAG, not a tree — 27 materials have more than one parent.
    All parents are emitted and the ancestry walk is breadth first, so nothing depends
    on which parent happens to be listed first.
  * 155 of the 310 material entries have no English name, all of them recycling codes
    like `xx:84-c-pap`. A name is composed from the parent concept and the code rather
    than showing a user "84 c pap".
  * The localised names go to a bundled JSON resource rather than into Swift. There are
    thousands of them, and a Swift dictionary literal that size does not type check in
    any reasonable time — a sixteen element literal in this project already had to be
    broken up for that reason.

Ambiguous localised names are dropped rather than guessed at, and reported, because a
synonym that maps one word onto two different materials is worse than no synonym.
"""

import json
import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURES = os.path.join(ROOT, "Tools", "Fixtures")


def load(name):
    with open(os.path.join(FIXTURES, name), encoding="utf-8") as handle:
        return json.load(handle)


def english_name(entry):
    return ((entry.get("name") or {}).get("en") or "").strip()


def composed_name(key, entry, table):
    """A readable name for an entry the taxonomy never named in English."""
    code = key.split(":", 1)[1].upper().replace("-", "/")
    for parent in entry.get("parents") or []:
        parent_name = english_name(table.get(parent, {}))
        if parent_name:
            return "%s (%s)" % (parent_name, code)
    return code


def fold(text):
    """Reduce a contributed name to a bare comparable term.

    Must stay identical to TaxonomyID.folded on the Swift side, which is what makes
    "es:Plástico", "es:plastico" and "ES: Plástico " all arrive at the same place.
    """
    decomposed = unicodedata.normalize("NFD", text.lower())
    stripped = "".join(c for c in decomposed if not unicodedata.combining(c))
    out = []
    for char in stripped:
        out.append(char if char.isalnum() else "-")
    return "-".join(part for part in "".join(out).split("-") if part)


def localized(table):
    """lang:folded-name -> canonical id, for every language the taxonomy names."""
    seen = {}
    collisions = set()
    for key, entry in table.items():
        for lang, name in (entry.get("name") or {}).items():
            term = fold(name)
            if not term:
                continue
            handle = "%s:%s" % (lang, term)
            existing = seen.get(handle)
            if existing is None:
                seen[handle] = key
            elif existing != key:
                collisions.add(handle)

    # A name already equal to its own id teaches nothing.
    resolved = {
        handle: key
        for handle, key in seen.items()
        if handle not in collisions and handle != key
    }
    return resolved, sorted(collisions)


def swift_dictionary(name, pairs, value):
    lines = ["    static let %s: [TaxonomyID: %s] = [" % (name, value)]
    for key, item in sorted(pairs):
        lines.append('        "%s": %s,' % (key, item))
    lines.append("    ]")
    return "\n".join(lines)


def quoted(text):
    return '"%s"' % text.replace("\\", "\\\\").replace('"', '\\"')


def build(table):
    parents = []
    names = []
    for key, entry in table.items():
        own = entry.get("parents") or []
        if own:
            parents.append((key, "[%s]" % ", ".join(quoted(p) for p in own)))
        name = english_name(entry) or composed_name(key, entry, table)
        names.append((key, quoted(name)))
    return parents, names


def main():
    materials = load("off-packaging-materials.json")
    shapes = load("off-packaging-shapes.json")

    material_parents, material_names = build(materials)
    shape_parents, shape_names = build(shapes)

    out = ['''// Generated by Tools/generate-taxonomy.py from the vendored Open Food Facts
// taxonomy snapshots in Tools/Fixtures. Do not edit by hand — run
// ./Tools/refresh-taxonomy.sh instead.
//
// Open Food Facts publishes its packaging taxonomies, so BinMate reads them rather
// than guessing at identifiers. Everything a scan can return is in here, which is
// the point: ./Tools/verify-taxonomy.sh fails if any entry below cannot be placed.

import Foundation

enum OFFTaxonomy {
    /// Every parent, not the first one. The taxonomy is a DAG: 27 materials have more
    /// than one parent, so picking one would quietly decide which city rule a material
    /// inherits. The ancestry walk visits all of them, nearest first.''']
    out.append(swift_dictionary("materialParents", material_parents, "[TaxonomyID]"))
    out.append("")
    out.append("    /// English names as published, except for the recycling codes the")
    out.append("    /// taxonomy never named, which are composed from their parent concept.")
    out.append(swift_dictionary("materialNames", material_names, "String"))
    out.append("")
    out.append(swift_dictionary("shapeParents", shape_parents, "[TaxonomyID]"))
    out.append("")
    out.append(swift_dictionary("shapeNames", shape_names, "String"))
    out.append("}")

    material_synonyms, material_collisions = localized(materials)
    shape_synonyms, shape_collisions = localized(shapes)

    synonyms_path = os.path.join(ROOT, "BinMate", "Resources", "off-synonyms.json")
    with open(synonyms_path, "w", encoding="utf-8") as handle:
        json.dump(
            {"materials": material_synonyms, "shapes": shape_synonyms},
            handle,
            ensure_ascii=False,
            indent=0,
            sort_keys=True,
        )
        handle.write("\n")

    destination = os.path.join(ROOT, "BinMate", "Model", "OFFTaxonomy+Generated.swift")
    with open(destination, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out) + "\n")

    print("materials: %d entries, %d with parents" % (len(materials), len(material_parents)))
    print("shapes:    %d entries, %d with parents" % (len(shapes), len(shape_parents)))
    print("synonyms:  %d material, %d shape, across every language the taxonomy names"
          % (len(material_synonyms), len(shape_synonyms)))
    if material_collisions or shape_collisions:
        print("dropped as ambiguous: %d material, %d shape"
              % (len(material_collisions), len(shape_collisions)))
        for handle in (material_collisions + shape_collisions)[:12]:
            print("    %s" % handle)
    print("wrote %s" % os.path.relpath(synonyms_path, ROOT))
    print("wrote %s" % os.path.relpath(destination, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
